int cvi_board_init(void)
{
	/* Camera */
	PINMUX_CONFIG(CAM_MCLK0, CAM_MCLK0);      /* CAM-MCLK */
	PINMUX_CONFIG(CAM_PD0, XGPIOA_1);         /* CAM-PD, GPIO481 */
	PINMUX_CONFIG(CAM_RST0, XGPIOA_2);        /* CAM-RSTn, GPIO482 */
	PINMUX_CONFIG(IIC3_SCL, IIC3_SCL);        /* CAM-SCL */
	PINMUX_CONFIG(IIC3_SDA, IIC3_SDA);        /* CAM-SDA */
	mmio_clrsetbits_32(0x03001b14, 0xc, 0x4); /* CAM-SCL pull-up */
	mmio_clrsetbits_32(0x03001b18, 0xc, 0x4); /* CAM-SDA pull-up */
	PINMUX_CONFIG(PAD_MIPIRX4N, XGPIOC_2);    /* CAM0 PAD_MIPIRX4N, GPIO418 */
	PINMUX_CONFIG(PAD_MIPIRX4P, XGPIOC_3);    /* CAM0 PAD_MIPIRX4P, GPIO419 */

	/* Motor UART and SPI */
	PINMUX_CONFIG(IIC0_SDA, UART1_RX);        /* MOTOR-TXD */
	PINMUX_CONFIG(IIC0_SCL, UART1_TX);        /* MOTOR-RXD */
	PINMUX_CONFIG(PAD_MIPI_TXP1, SPI0_SDI);   /* MOTOR-MISO */
	PINMUX_CONFIG(PAD_MIPI_TXM1, SPI0_SDO);   /* MOTOR-MOSI */
	PINMUX_CONFIG(PAD_MIPI_TXP2, SPI0_CS_X);  /* MOTOR-CS */
	PINMUX_CONFIG(PAD_MIPI_TXM2, SPI0_SCK);   /* MOTOR-SCLK */
	PINMUX_CONFIG(PAD_MIPI_TXP3, XGPIOC_21);  /* MOTOR-RSTn, GPIO437 */

	/* Zoom camera control */
	PINMUX_CONFIG(PAD_MIPI_TXM3, XGPIOC_20);  /* VD-IS, GPIO436 */
	PINMUX_CONFIG(PAD_MIPI_TXP4, XGPIOC_19);  /* GPIO-FZ, GPIO435 */

	/* Laser rangefinder */
	PINMUX_CONFIG(SD1_D1, UART3_RX);          /* LASER-TXD */
	PINMUX_CONFIG(SD1_D2, UART3_TX);          /* LASER-RXD */
	PINMUX_CONFIG(SD1_CMD, PWR_GPIO_22);      /* LASER-EN, GPIO374 */
	PINMUX_CONFIG(SD1_CLK, PWR_GPIO_23);      /* LASER-5V-EN, GPIO375 */

	/* Lens position feedback and IMU */
	PINMUX_CONFIG(VIVO_D0, XGPIOB_21);        /* ZOOM1-PI, GPIO469 */
	PINMUX_CONFIG(VIVO_D1, XGPIOB_20);        /* ZOOM2-PI, GPIO468 */
	PINMUX_CONFIG(VIVO_D2, XGPIOB_19);        /* ZOOM3-PI, GPIO467 */
	PINMUX_CONFIG(VIVO_D3, XGPIOB_18);        /* FOCUS-PI, GPIO466 */
	PINMUX_CONFIG(VIVO_D4, XGPIOB_17);        /* IMU-INT, GPIO465 */
	PINMUX_CONFIG(VIVO_D5, SPI3_CS_X);        /* IMU-CSn */
	PINMUX_CONFIG(VIVO_D6, SPI3_SCK);         /* IMU-SCLK */
	PINMUX_CONFIG(VIVO_D7, SPI3_SDI);         /* IMU-MISO */
	PINMUX_CONFIG(VIVO_D8, SPI3_SDO);         /* IMU-MOSI */

	/* Flight controller */
	PINMUX_CONFIG(VIVO_D9, UART2_RX);         /* SOC-UART2-RXD */
	PINMUX_CONFIG(VIVO_D10, UART2_TX);        /* SOC-UART2-TXD */
	PINMUX_CONFIG(VIVO_CLK, XGPIOB_22);       /* FLY-UART-EN, GPIO470 */

	/* Enable PWM. */
	mmio_setbits_32(0x030002d0, 1 << 9);

	return 0;
}
