#define OVIS_CVBS_SD_PWRSW_CTRL	(TOP_BASE + 0x1F4)
#define OVIS_CVBS_SD_PWRSW_MASK	0xF
#define OVIS_CVBS_SD_PWRSW_1V8	0xB

int cvi_board_init(void)
{
#if 0 /* pinmux set in alios */
	PINMUX_CONFIG(CAM_MCLK0, CAM_MCLK0);

	PINMUX_CONFIG(IIC2_SCL, IIC2_SCL);
	PINMUX_CONFIG(IIC2_SDA, IIC2_SDA);

	PINMUX_CONFIG(IIC3_SCL, IIC3_SCL);
	PINMUX_CONFIG(IIC3_SDA, IIC3_SDA);
#endif
	//enable pwm
	mmio_setbits_32(0x030002d0, 1 << 9);

	//CAM
	PINMUX_CONFIG(CAM_MCLK0, CAM_MCLK0);
	PINMUX_CONFIG(PWR_GPIO0, PWR_GPIO_0);//PWDNB
	PINMUX_CONFIG(PWR_GPIO1, PWR_GPIO_1);//XSHUTDN
	PINMUX_CONFIG(IIC3_SDA, IIC3_SDA);//IIC3
	PINMUX_CONFIG(IIC3_SCL, IIC3_SCL);//IIC3
	PINMUX_CONFIG(IIC0_SDA, XGPIOA_29);//GPIO
	PINMUX_CONFIG(IIC0_SCL, XGPIOA_28);//GPIO
	PINMUX_CONFIG(PAD_MIPIRX4N, XGPIOC_2); //CAM0 PAD_MIPIRX4N
	PINMUX_CONFIG(PAD_MIPIRX4P, XGPIOC_3); //CAM0 PAD_MIPIRX4P

	//CVBS
	//VDDIO_SD0 powers the I2C level shifter and its output enable.
	mmio_clrsetbits_32(OVIS_CVBS_SD_PWRSW_CTRL,
		OVIS_CVBS_SD_PWRSW_MASK, OVIS_CVBS_SD_PWRSW_1V8);
	mdelay(1);
	PINMUX_CONFIG(IIC2_SCL, IIC2_SCL);
	PINMUX_CONFIG(IIC2_SDA, IIC2_SDA);
	PINMUX_CONFIG(VIVO_D2, VO_D_15);
	PINMUX_CONFIG(VIVO_D3, VO_D_16);
	PINMUX_CONFIG(VIVO_D4, VO_D_17);
	PINMUX_CONFIG(VIVO_D5, VO_D_18);
	PINMUX_CONFIG(VIVO_D6, VO_D_19);
	PINMUX_CONFIG(VIVO_D7, VO_D_20);
	PINMUX_CONFIG(VIVO_D8, VO_D_21);
	PINMUX_CONFIG(VIVO_D9, VO_D_22);
	PINMUX_CONFIG(VIVO_CLK, VO_CLK1);
	PINMUX_CONFIG(SD0_CD, XGPIOA_13); //MS7024 RSTN
	PINMUX_CONFIG(SD0_PWR_EN, XGPIOA_14); //MS7024 DEIN


	//UART
	PINMUX_CONFIG(JTAG_CPU_TCK, UART1_RX);//UART1
	PINMUX_CONFIG(JTAG_CPU_TMS, UART1_TX);//UART1


	return 0;
}

